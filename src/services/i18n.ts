class I18nService {
  private currentLang: string = 'en';
  private listeners: Array<(lang: string) => void> = [];

  constructor() {
    if (typeof window !== 'undefined') {
      const saved = storageService.getLanguage();
      if (saved && SUPPORTED_LANGUAGES.some(l => l.code === saved)) {
        this.currentLang = saved;
      } else {
        // Auto-detect device language
        const userLangs = (navigator.languages && navigator.languages.length > 0)
          ? Array.from(navigator.languages)
          : [navigator.language || 'en'];
        
        let matched = false;
        for (const userLang of userLangs) {
          if (!userLang) continue;
          const clean = userLang.toLowerCase();
          
          // Exact match (e.g. 'zh-cn' -> 'zh-CN')
          const exact = SUPPORTED_LANGUAGES.find(l => l.code.toLowerCase() === clean);
          if (exact) {
            this.currentLang = exact.code;
            matched = true;
            break;
          }
          
          // Primary language code match (e.g. 'vi-vn' -> 'vi', 'es-es' -> 'es')
          const primary = clean.split(/[-_]/)[0];
          const primaryMatch = SUPPORTED_LANGUAGES.find(l => l.code.toLowerCase().split(/[-_]/)[0] === primary);
          if (primaryMatch) {
            this.currentLang = primaryMatch.code;
            matched = true;
            break;
          }
        }
        
        if (!matched) {
          this.currentLang = 'en';
        }
      }
      this.applyDir();
    }
  }

  public getLanguage(): string {
    return this.currentLang;
  }

  public getLanguageMeta(): LanguageMeta {
    return (
      SUPPORTED_LANGUAGES.find(l => l.code === this.currentLang) ||
      SUPPORTED_LANGUAGES[0]
    );
  }

  public setLanguage(code: string): void {
    if (!SUPPORTED_LANGUAGES.some(l => l.code === code)) return;
    this.currentLang = code;
    if (typeof window !== 'undefined') {
      storageService.saveLanguage(code);
      this.applyDir();
    }
    this.listeners.forEach(fn => fn(code));
  }

  public t(key: TranslationKey, fallback?: string): string {
    const langDict = TRANSLATIONS[this.currentLang];
    if (langDict && langDict[key]) {
      return langDict[key]!;
    }
    // Fallback to English
    const enDict = TRANSLATIONS['en'];
    if (enDict && enDict[key]) {
      return enDict[key]!;
    }
    return fallback || key;
  }

  public subscribe(callback: (lang: string) => void): () => void {
    this.listeners.push(callback);
    return () => {
      this.listeners = this.listeners.filter(cb => cb !== callback);
    };
  }

  private applyDir() {
    if (typeof document === 'undefined') return;
    const meta = this.getLanguageMeta();
    document.documentElement.dir = meta.dir;
    document.documentElement.lang = meta.code;
  }
}

export const i18n = new I18nService();

export function useTranslation() {
  const [currentLang, setCurrentLang] = ReactState();

  return {
    t: (key: TranslationKey, fallback?: string) => i18n.t(key, fallback),
    language: currentLang,
    currentLanguage: currentLang,
    setLanguage: (code: string) => i18n.setLanguage(code),
    languageMeta: i18n.getLanguageMeta(),
    languages: SUPPORTED_LANGUAGES,
    supportedLanguages: SUPPORTED_LANGUAGES
  };
}

function ReactState() {
  const [lang, setLang] = useState(i18n.getLanguage());
  useEffect(() => {
    return i18n.subscribe((newLang) => setLang(newLang));
  }, []);
  return [lang, setLang] as const;
}
